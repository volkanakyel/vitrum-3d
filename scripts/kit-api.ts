/**
 * Render the hand-written sculpt kit contract (`kit.d.ts`) into the Markdown
 * that is pasted into the model's prompt. Run `pnpm kit-api` whenever
 * `kit.d.ts` changes.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const source = resolve(root, 'app/utils/sculpt/kit/kit.d.ts')
const target = resolve(root, 'server/utils/sculpt/prompts/kit-api.md')

const declarations = readFileSync(source, 'utf8')
  .split('\n')
  .filter(line => !/^\s*import\s/.test(line))
  .map(line => line.replace(/^export\s+/, ''))
  .join('\n')
  .replace(/\n{3,}/g, '\n\n')
  .trim()

const markdown = `<!-- generated by scripts/kit-api.ts from app/utils/sculpt/kit/kit.d.ts — do not edit -->

## Sculpt kit API

\`\`\`ts
${declarations}
\`\`\`
`

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, markdown, 'utf8')
process.stdout.write(`kit-api: wrote ${target}\n`)
