/**
 * Render the hand-written sculpt kit contract (`kit.d.ts`) into the Markdown
 * that is pasted into the model's prompt. Run `pnpm kit-api` whenever
 * `kit.d.ts` changes.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
export const KIT_TYPES_PATH = resolve(root, 'app/utils/sculpt/kit/kit.d.ts')
export const KIT_API_PATH = resolve(root, 'server/utils/sculpt/prompts/kit-api.md')

/** Render `kit.d.ts` as the Markdown block pasted into the model's prompt. */
export function renderKitApi(types: string): string {
  const declarations = types
    .split('\n')
    .filter(line => !/^\s*import\s/.test(line))
    .map(line => line.replace(/^export\s+/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()

  return `<!-- generated by scripts/kit-api.ts from app/utils/sculpt/kit/kit.d.ts — do not edit -->

## Sculpt kit API

\`\`\`ts
${declarations}
\`\`\`
`
}

export function writeKitApi(): string {
  const markdown = renderKitApi(readFileSync(KIT_TYPES_PATH, 'utf8'))
  mkdirSync(dirname(KIT_API_PATH), { recursive: true })
  writeFileSync(KIT_API_PATH, markdown, 'utf8')
  return KIT_API_PATH
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.stdout.write(`kit-api: wrote ${writeKitApi()}\n`)
}
